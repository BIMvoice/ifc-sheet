/**
 * Which face the app shows. `sheet` is IfcSheet's own: the Wall full screen,
 * a sheet stepped into with its six tools, nothing else. `classic` is the
 * engine's full interface (ribbon, navigator, panels), kept one step away
 * behind "More" for whatever the six tools do not cover.
 *
 * The classic layout stays mounted underneath either way: the 3D viewport
 * hosts the drawing runtime every view's drawing is generated by.
 */

import { create } from 'zustand';
import { isDocsEdition } from '@/edition';

export type ShellMode = 'sheet' | 'classic';

export const useShellMode = create<{ mode: ShellMode }>()(() => ({ mode: isDocsEdition() ? 'sheet' : 'classic' }));

export function setShellMode(mode: ShellMode): void {
  useShellMode.setState({ mode });
}

export const isSheetShell = (): boolean => useShellMode.getState().mode === 'sheet';
